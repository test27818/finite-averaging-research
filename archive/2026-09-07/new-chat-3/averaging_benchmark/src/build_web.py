#!/usr/bin/env python3
"""Build the offline HTML script blocks and CommonJS compatibility bundle.

Maintained sources: web_{solver,verifier,runner,main,compat}.js.
solver.html is the UI/CSS template AND the distributable (scripts replaced by this).
Run --check in tests/CI to ensure the browser and Node use the same implementation.
"""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = [('solver-source','web_solver.js'), ('verifier-source','web_verifier.js'),
           ('runner-source','web_runner.js'), ('main-source','web_main.js')]


def build(check=False):
    path = ROOT/'solver.html'
    html = path.read_text()
    for sid, name in SCRIPTS:
        source = (ROOT/'src'/name).read_text().strip()
        pattern = r'(<script id="'+sid+r'"[^>]*>).*?(</script>)'
        html, count = re.subn(pattern, lambda m: m[1]+'\n'+source+'\n'+m[2], html, flags=re.S)
        if count != 1:
            raise ValueError('missing/duplicate script block: '+sid)
    # Concatenate within one CommonJS scope so all internal exact routines are shared.
    bundle = '// GENERATED by build_web.py; edit web_*.js, not this file.\n'
    bundle += '\n'.join((ROOT/'src'/name).read_text() for name in
                        ['web_solver.js','web_verifier.js','web_runner.js','web_compat.js'])
    outputs = [(path, html), (ROOT/'src/solver_core.js', bundle)]
    for dst, data in outputs:
        if check:
            if not dst.exists() or dst.read_text() != data:
                print('OUT OF SYNC:', dst)
                return False
        else:
            dst.write_text(data)
            print('built', dst)
    return True


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    sys.exit(0 if build(args.check) else 1)
